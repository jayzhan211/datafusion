-- #26285 outer column whose type is set by coercion (UNION ALL of INT and BIGINT)
CREATE TABLE a(k INT) AS VALUES (1), (100000);
CREATE TABLE b(k BIGINT) AS VALUES (3);
CREATE TABLE u(c0 INT) AS VALUES (1), (3), (100000);
SELECT s.k FROM (SELECT k FROM a UNION ALL SELECT k FROM b) s WHERE EXISTS (SELECT 1 FROM u WHERE u.c0 = s.k) ORDER BY 1;
