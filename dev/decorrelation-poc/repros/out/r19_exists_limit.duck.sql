-- #26629 LIMIT inside EXISTS below a HAVING
CREATE TABLE a(k INT, x INT); INSERT INTO a VALUES (1, 10), (2, 20);
CREATE TABLE b(k INT, v INT); INSERT INTO b VALUES (1, 100), (1, 200), (2, 300);
SELECT a.k FROM a WHERE EXISTS (SELECT 1 FROM (SELECT b.k, b.v FROM b WHERE b.k = a.k LIMIT 1) sub HAVING COUNT(*) > 1) ORDER BY 1;
